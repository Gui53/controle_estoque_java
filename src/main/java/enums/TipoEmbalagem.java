package enums;

/**
 * Enumeração que representa os tipos de embalagem
 * disponíveis para as categorias de produtos.
 *
 * Os valores definidos são utilizados para classificar
 * a forma de armazenamento ou comercialização dos produtos.
 *
 * @author Gabriel Conci
 * @version 1.0
 * @since 2026
 */
public enum TipoEmbalagem {

    /**
     * Produto armazenado em embalagem do tipo lata.
     */
    LATA,

    /**
     * Produto armazenado em embalagem de vidro.
     */
    VIDRO,

    /**
     * Produto armazenado em embalagem plástica.
     */
    PLASTICO
}