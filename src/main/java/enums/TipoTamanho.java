package enums;

/**
 * Enumeração que representa os tamanhos disponíveis
 * para as categorias de produtos cadastradas no sistema.
 *
 * Os valores definidos permitem classificar os produtos
 * conforme seu porte ou volume.
 *
 * @author Gabriel Conci
 * @version 1.0
 * @since 2026
 */
public enum TipoTamanho {

    /**
     * Representa um produto de pequeno porte.
     */
    PEQUENO,

    /**
     * Representa um produto de porte médio.
     */
    MEDIO,

    /**
     * Representa um produto de grande porte.
     */
    GRANDE
}